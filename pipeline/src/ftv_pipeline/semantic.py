"""Semantic identity sliders: one slider ≈ one facial feature (nose width, jaw width, …).

GNM's identity components are PCA modes, and each one changes many features at once. A semantic
slider is instead ONE direction `u` over all 170 head_* components. It is solved so that it changes
its own measurement a lot (e.g. the distance between the two alare points = nose width), keeps every
other slider's measurement where it was, and barely moves the face outside its own region.

GNM is linear, so every measurement is (nearly) linear in the coefficients c (σ units):

    m(c) ≈ m(0) + J c        J: (K measurements × 170 components), millimetres per σ

For slider k we minimise

    w_own (J_k c − δ)²  +  w_cross Σ_{j≠k, not free} (J_j c)²  +  cᵀ (I + λ_out Q_out + λ_sym Q_sym) c

  I      the model's own prior (coefficients are N(0, 1)): prefer the most likely face change
  Q_out  mean-square displacement outside the slider's region (mm², soft edge falloff_mm)
  Q_sym  mean-square left/right asymmetry of the displacement (mm²)

The own term has rank one, so (Sherman–Morrison) the direction does not depend on w_own or δ:

    u ∝ N⁻¹ J_kᵀ,     N = I + λ_out Q_out + λ_sym Q_sym + w_cross Σ_{j≠k} J_jᵀ J_j

Scale: at morph weight ±1 the feature sits at ±`target_pop_sigma` population standard deviations
(the measurement's σ over GNM faces is ‖J_k‖, since coefficients are N(0, 1)), so the slider spans
"narrow … wide as real people are". The coefficient vector is capped at `max_sigma` (Mahalanobis
length; a typical random face lies ~13σ from the mean in 170 dimensions), which keeps expensive,
highly constrained directions from leaving the model's statistics. `scale_sigma` on a slider
overrides both.

Config: config/semantic_sliders.toml. Commands (run from /pipeline):
    uv run semantic-landmarks [--write]   propose landmark vertices and render out/semantic/landmarks.png
    uv run semantic-report [--check]      solve, then write out/semantic/report.md, sheet.png, directions.npz
"""

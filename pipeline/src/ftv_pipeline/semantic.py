def report_main(argv=None) -> None:
    p = argparse.ArgumentParser(description="Solve the semantic sliders and write the report + contact sheet.")
    p.add_argument("--no-sheet", action="store_true", help="skip the contact sheet (report only)")
    p.add_argument("--size", type=int, default=300)
    p.add_argument("--check", action="store_true", help="exit 1 unless every slider passes the quality gates below")
    args = p.parse_args(argv)
    t0 = time.time()
    gnm = GNM.load()
    cfg = load_config()
    sol = solve(gnm, cfg)
    t_solve = time.time() - t0
    rows = evaluate(gnm, sol)
    cover = coverage(gnm, sol)
    SEM_OUT.mkdir(parents=True, exist_ok=True)
    np.savez(SEM_OUT / "directions.npz", ids=np.array(sol.ids), components=np.array(sol.components),
             coefficients=sol.coefficients.astype(np.float32))
    (SEM_OUT / "report.json").write_text(json.dumps(rows, indent=1))
    print(write_report(rows, sol, SEM_OUT / "report.md", cover))
    print(f"solved {len(sol.ids)} sliders over {len(sol.components)} components in {t_solve:.1f} s")
    failures = check(rows)
    for f in failures:
        print("FAIL", f)
    print("quality gates:", "PASS" if not failures else f"{len(failures)} failure(s)")
    if not args.no_sheet:
        render_sheet(gnm, sol, cfg, rows, SEM_OUT / "sheet.png", args.size)
        print(f"-> {SEM_OUT / 'sheet.png'}")
    if args.check and failures:
        raise SystemExit(1)

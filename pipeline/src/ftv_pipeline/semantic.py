# --- landmarks -----------------------------------------------------------------------------------


@dataclass
class Landmark:
    indices: list[int]  # one vertex, or a small set whose mean position is used
    rule: str  # how it was found (written as a comment next to the index)


def _ring(gnm: GNM, inner: np.ndarray) -> np.ndarray:
    """Outer-skin vertices that share a triangle with `inner` (the rim of the eye or mouth opening)."""
    ext = gnm.vertex_groups["skin_exterior"]
    touch = inner[gnm.triangles].any(axis=1)
    rim = np.unique(gnm.triangles[touch])
    return rim[ext[rim]]


def propose_landmarks(gnm: GNM) -> dict[str, Landmark]:
    """Pick anthropometric landmark vertices on the GNM template from simple geometric rules.

    Left-side points (+X is the head's left) are found by rule; the "_r" twin is the GNM mirror vertex.
    """
    T, g = gnm.template, gnm.vertex_groups
    ext = g["skin_exterior"]
    x, y, z = T[:, 0], T[:, 1], T[:, 2]
    mid = ext & (np.abs(x) < MIDLINE_X) & (z > 0.06)  # front half of the midline profile

    def pick(mask: np.ndarray, key: np.ndarray, largest: bool) -> int:
        idx = np.flatnonzero(mask)
        if not len(idx):
            raise RuntimeError("landmark rule matched no vertex")
        return int(idx[np.argmax(key[idx]) if largest else np.argmin(key[idx])])

    L: dict[str, Landmark] = {}

    def add(name: str, i: int | list[int], rule: str, mirror: bool = False) -> None:
        ids = [int(v) for v in np.atleast_1d(i)]
        if mirror:
            L[f"{name}_l"] = Landmark(ids, rule)
            L[f"{name}_r"] = Landmark([int(gnm.mirror[v]) for v in ids], "mirror of " + name + "_l")
        else:
            L[name] = Landmark(ids, rule)

    # midline profile, top to bottom
    add("trichion", pick(mid & g["forehead_region"], y, True), "forehead_region, midline, highest (hairline)")
    add("glabella", pick(mid & (y > 0.31) & (y < 0.345), z, True), "midline, y 0.310–0.345, most forward (between the brows)")
    add("nasion", pick(mid & (y > 0.285) & (y < 0.315), z, False), "midline, y 0.285–0.315, deepest (root of the nose)")
    prn = pick(mid & g["nose_region"], z, True)
    add("pronasale", prn, "nose_region, midline, most forward (nose tip)")
    sn = pick(mid & g["nose_region"], y, False)
    add("subnasale", sn, "nose_region, midline, lowest (where the nose meets the lip)")
    add("labrale_superius", pick(mid & g["upper_lip"], y, True), "upper_lip (red lip), midline, highest")
    li = pick(mid & g["lower_lip"], y, False)
    add("labrale_inferius", li, "lower_lip (red lip), midline, lowest")
    add("sublabiale", pick(mid & (y < y[li]) & (y > y[li] - 0.015), z, False), "midline, ≤15 mm below labrale_inferius, deepest (chin crease)")
    add("menton", pick(mid & g["chin_region"], y, False), "chin_region, midline, lowest")

    # eyes: the rim of the eye opening (skin next to the eye socket)
    rim = _ring(gnm, g["eye_sockets"])
    left_rim = np.zeros(len(T), bool)
    left_rim[rim[x[rim] > 0]] = True
    en = pick(left_rim, x, False)
    ex = pick(left_rim, x, True)
    add("endocanthion", en, "eye-opening rim, innermost (inner eye corner)", mirror=True)
    add("exocanthion", ex, "eye-opening rim, outermost (outer eye corner)", mirror=True)
    add("lid_upper", pick(left_rim, y, True), "eye-opening rim, highest (upper lid margin)", mirror=True)
    add("lid_lower", pick(left_rim, y, False), "eye-opening rim, lowest (lower lid margin)", mirror=True)
    add("canthi", [en, ex], "both eye corners (vertical reference for the brow)", mirror=True)
    pupil_x = float(T[ex, 0] + T[en, 0]) / 2
    brow = np.flatnonzero(g["left_brow_region"] & ext & (np.abs(x - pupil_x) < 0.003))
    add("brow", brow.tolist(), "left_brow_region within 3 mm of the eye's centre line (whole brow height)", mirror=True)
    # brow ends, for expression goals (emotions.py): inner = the 5 mm nearest the midline, outer = the last 8 mm
    brow_all = g["left_brow_region"] & ext
    bx = x[brow_all]
    add("brow_inner", np.flatnonzero(brow_all & (x < bx.min() + 0.005)).tolist(), "left_brow_region, innermost 5 mm (inner brow)", mirror=True)
    add("brow_outer", np.flatnonzero(brow_all & (x > bx.max() - 0.008)).tolist(), "left_brow_region, outermost 8 mm (brow tail)", mirror=True)

    # nose and mouth
    add("alare", pick(g["nose_region"] & ext & (y > y[sn]) & (y < y[sn] + 0.012) & (x > 0), x, True),
        "nose_region, ≤12 mm above subnasale, widest (nostril wing)", mirror=True)
    mouth_rim = _ring(gnm, g["mouth_sock"])
    left_mouth = np.zeros(len(T), bool)
    left_mouth[mouth_rim[x[mouth_rim] > 0]] = True
    add("cheilion", pick(left_mouth, x, True), "mouth-opening rim, outermost (mouth corner)", mirror=True)
    mouth_mid = np.zeros(len(T), bool)
    mouth_mid[mouth_rim[np.abs(x[mouth_rim]) < MIDLINE_X]] = True
    # by lip group, not by height: the closed lips overlap, so the upper lip's edge sits 0.8 mm BELOW the lower one's
    add("stomion_upper", pick(mouth_mid & g["upper_lip"], y, False), "mouth-opening rim, midline, on the upper lip (its inner edge)")
    add("stomion_lower", pick(mouth_mid & g["lower_lip"], y, True), "mouth-opening rim, midline, on the lower lip (its inner edge)")

    # jaw angle: just in front of the ear, where the side of the face turns into the underside of the
    # jaw (the surface normal closest to 45° outwards-and-down)
    normals = vertex_normals(T, gnm.triangles)
    corner = normals @ (np.array([1.0, -1.0, 0.0]) / np.sqrt(2))
    band = ext & (x > 0.03) & (z > 0.025) & (z < 0.05) & (y > 0.18) & (y < 0.24)
    add("gonion", pick(band, corner, True), "side of the jaw in front of the ear, normal closest to 45° out-and-down (jaw angle)", mirror=True)

    # skull
    back = ext & (np.abs(x) < MIDLINE_X) & (z < 0)
    add("vertex", pick(ext & (np.abs(x) < MIDLINE_X), y, True), "midline, highest (top of the head)")
    add("opisthocranion", pick(back & (y > 0.26) & (y < 0.36), z, False), "midline, y 0.26–0.36, furthest back (back of the skull)")
    ears = g["ears"]
    add("euryon", pick(ext & ~ears & (y > 0.30) & (x > 0), x, True), "above the ears, widest point of the skull", mirror=True)
    # cheekbones and chin
    add("zygion", pick(g["left_zygomatic_region"] & ext, x, True), "left_zygomatic_region, widest (cheekbone)", mirror=True)
    pog = pick(mid & g["chin_region"], z, True)
    add("pogonion", pog, "chin_region, midline, most forward (chin point)")
    add("chin_side", pick(g["chin_region"] & ext & (np.abs(y - y[pog]) < 0.004) & (x > 0), x, True),
        "chin_region at the chin point's height, widest", mirror=True)
    # ears: top, bottom, outermost rim point, and the ring where the ear joins the head
    left_ear = ears & ext & (x > 0)
    add("ear_top", pick(left_ear, y, True), "left ear, highest", mirror=True)
    add("ear_bottom", pick(left_ear, y, False), "left ear, lowest (lobe)", mirror=True)
    add("ear_out", pick(left_ear, x, True), "left ear, furthest out (rim)", mirror=True)
    head_skin = ext & ~ears
    root = np.unique(gnm.triangles[(ears[gnm.triangles].any(axis=1)) & (head_skin[gnm.triangles].any(axis=1))])
    root = root[left_ear[root]]
    add("ear_root", root.tolist(), "left ear vertices that touch the head skin (where the ear joins the head)", mirror=True)
    return L


def _format_landmarks(L: dict[str, Landmark]) -> str:
    lines = [LANDMARKS_BEGIN, "[landmarks]"]
    for name, lm in L.items():
        value = str(lm.indices[0]) if len(lm.indices) == 1 else "[" + ", ".join(map(str, lm.indices)) + "]"
        lines.append(f"{name} = {value}".ljust(34) + f"  # {lm.rule}")
    lines.append(LANDMARKS_END)
    return "\n".join(lines) + "\n"


def write_landmarks(L: dict[str, Landmark], path: Path = CONFIG) -> None:
    """Replace (or append) the generated [landmarks] block of the config, keeping everything else."""
    text = path.read_text()
    block = _format_landmarks(L)
    pattern = re.compile(re.escape(LANDMARKS_BEGIN) + r".*?" + re.escape(LANDMARKS_END) + r"\n?", re.S)
    text = pattern.sub(block, text) if pattern.search(text) else text.rstrip("\n") + "\n\n" + block
    path.write_text(text)


# --- config + measurements --------------------------------------------------------------------------


def load_config(path: Path = CONFIG) -> dict:
    with open(path, "rb") as f:
        cfg = tomllib.load(f)
    ids = [s["id"] for s in cfg["slider"]]
    if len(set(ids)) != len(ids):
        raise ValueError(f"duplicate slider ids in {path.name}")
    for s in cfg["slider"]:
        for f in s.get("free", []):
            if f != "*" and f not in ids:
                raise ValueError(f"{s['id']}: free = {f!r} is not a slider id")
        if s.get("bake", "auto") not in (True, False, "auto"):
            raise ValueError(f"{s['id']}: bake must be true, false or \"auto\"")
    return cfg


def config_landmarks(cfg: dict) -> dict[str, np.ndarray]:
    if "landmarks" not in cfg:
        raise SystemExit("no [landmarks] in semantic_sliders.toml yet: run `uv run semantic-landmarks --write`")
    return {k: np.atleast_1d(np.asarray(v, np.int64)) for k, v in cfg["landmarks"].items()}


AXES = {"x": 0, "y": 1, "z": 2}


@dataclass
class Measure:
    """A linearised measurement: value(P) in mm, and its gradient with respect to the vertex positions."""

    value: Callable[[np.ndarray], float]  # (V, 3) metres -> float mm
    grad: np.ndarray  # (V, 3) mm per metre of vertex movement, taken at the template


def build_measure(spec: dict, lm: dict[str, np.ndarray], gnm: GNM, normals: np.ndarray) -> Measure:
    T = gnm.template
    V = len(T)
    if "terms" in spec:
        parts = [(float(t.get("weight", 1.0)), build_measure(t, lm, gnm, normals)) for t in spec["terms"]]
        return Measure(lambda P: sum(w * m.value(P) for w, m in parts), sum(w * m.grad for w, m in parts))

    kind = spec["type"]
    if kind in ("distance", "axis"):
        pairs = [(lm[a], lm[b]) for a, b in spec["pairs"]]
        for a, b in spec["pairs"]:
            for n in (a, b):
                if n not in lm:
                    raise KeyError(f"unknown landmark {n!r}")
        grad = np.zeros((V, 3))
        if kind == "distance":
            def value(P):
                return 1000.0 * np.mean([np.linalg.norm(P[a].mean(0) - P[b].mean(0)) for a, b in pairs])
            for a, b in pairs:
                d = T[a].mean(0) - T[b].mean(0)
                u = d / np.linalg.norm(d)
                np.add.at(grad, a, 1000.0 * u / len(a) / len(pairs))
                np.add.at(grad, b, -1000.0 * u / len(b) / len(pairs))
        else:
            ax = AXES[spec["axis"]]
            def value(P):
                return 1000.0 * np.mean([P[a].mean(0)[ax] - P[b].mean(0)[ax] for a, b in pairs])
            for a, b in pairs:
                np.add.at(grad[:, ax], a, 1000.0 / len(a) / len(pairs))
                np.add.at(grad[:, ax], b, -1000.0 / len(b) / len(pairs))
        return Measure(value, grad)

    if kind == "normal":
        mask = np.zeros(V, bool)
        for grp in spec.get("groups", ["skin_exterior"]):
            mask |= gnm.vertex_groups[grp]
        mask &= gnm.vertex_groups["skin_exterior"]
        # optional bands (metres) to cut a part of the skin: y = [lo, hi], z = [lo, hi], x_abs_max = m
        for ax, key in ((1, "y"), (2, "z")):
            if key in spec:
                lo, hi = spec[key]
                mask &= (T[:, ax] >= lo) & (T[:, ax] <= hi)
        if "x_abs_max" in spec:
            mask &= np.abs(T[:, 0]) <= spec["x_abs_max"]
        if not mask.any():
            raise ValueError(f"normal measure selects no vertex: {spec}")
        idx = np.flatnonzero(mask)
        n = normals[idx]
        grad = np.zeros((V, 3))
        grad[idx] = 1000.0 * n / len(idx)
        return Measure(lambda P: 1000.0 * float(np.mean(np.einsum("ij,ij->i", P[idx] - T[idx], n))), grad)
    if kind == "balance":
        # a and b change in proportion to their own size: 0 when both grow by the same fraction
        ma, mb = build_measure(spec["a"], lm, gnm, normals), build_measure(spec["b"], lm, gnm, normals)
        a0, b0 = abs(ma.value(T)), abs(mb.value(T))
        k = (a0 + b0) / 2
        return Measure(lambda P: k * ((ma.value(P) - a0) / a0 - (mb.value(P) - b0) / b0), k * (ma.grad / a0 - mb.grad / b0))
    raise ValueError(f"unknown measure type {kind!r}")


# --- solver ------------------------------------------------------------------------------------------------


@dataclass
class Solution:
    ids: list[str]
    names: list[str]
    components: list[str]  # the identity components the directions are expressed in
    coefficients: np.ndarray  # (S, C) σ per component at morph weight 1.0
    J: np.ndarray  # (S, C) mm per σ, rows = each slider's own measurement
    pop_sigma: np.ndarray  # (S,) population σ of each measurement, mm (‖J_k‖)
    measures: list[Measure] = field(repr=False, default_factory=list)
    outside: list[np.ndarray] = field(repr=False, default_factory=list)  # (V,) outside weight per slider
    free: list[list[str]] = field(default_factory=list)  # per slider: measurements it may change (nested)
    guard_ids: list[str] = field(default_factory=list)  # measurements every slider holds fixed (not sliders)
    guard_measures: list[Measure] = field(repr=False, default_factory=list)
    baked: list[bool] = field(default_factory=list)  # True: own morph target; False: a mix of the shipped raw targets
    shipped: list[str] = field(default_factory=list)  # the raw head_* components head.glb ships (runtime mixes use these)
    choice: list[dict] = field(default_factory=list)  # per slider: how the baked and the runtime version compared
    held: list[bool] = field(default_factory=list)  # False: other sliders may change this measurement

    def combo(self, k: int, sigma_scale: float) -> dict[str, float]:
        """Runtime slider k as head.glb morph weights of the raw targets at weight 1.0 (weight = σ / sigma_scale)."""
        return {c: round(float(self.coefficients[k][self.components.index(c)]) / sigma_scale, 6) for c in self.shipped
                if abs(self.coefficients[k][self.components.index(c)]) > 1e-9}

    def delta(self, gnm: GNM, k: int) -> np.ndarray:
        """(V, 3) metres at morph weight 1.0 for slider k (exact: GNM is linear)."""
        idx = [gnm.identity_names.index(c) for c in self.components]
        return np.tensordot(self.coefficients[k].astype(np.float32), gnm.identity_basis[idx], axes=1)

    def joint_delta(self, gnm: GNM, k: int) -> np.ndarray:
        """(4, 3) metres at morph weight 1.0 — how the joints (eye pivots) move with slider k."""
        idx = [gnm.identity_names.index(c) for c in self.components]
        return np.tensordot(self.coefficients[k].astype(np.float32), gnm.joint_identity_basis[idx], axes=1)


def outside_weight(gnm: GNM, groups: list[str], falloff_mm: float, y_band: list[float] | None = None) -> np.ndarray:
    """1 far from the region, 0 inside it, a linear ramp over falloff_mm in between. `y_band` = [lo, hi] (metres):
    only the part of the groups at that height (GNM has no neck group: the neck is skin between two heights)."""
    inside = np.zeros(len(gnm.template), bool)
    for grp in groups:
        inside |= gnm.vertex_groups[grp]
    if y_band is not None:
        inside &= (gnm.template[:, 1] >= y_band[0]) & (gnm.template[:, 1] <= y_band[1])
    dist, _ = cKDTree(gnm.template[inside]).query(gnm.template)
    return np.clip(dist / (falloff_mm / 1000.0), 0.0, 1.0)


def shipped_components(gnm: GNM) -> list[str]:
    """The raw head_* identity components baked into head.glb (config/components.toml)."""
    from .export_glb import load_config as load_components

    return [c for c in load_components()["identity"]["components"] if gnm.region_of(c) == "head"]


# A runtime mix of the shipped raw targets replaces a baked target when it does nearly as well (costs no bytes):
COMBO_MIN_OWN = 0.85  # its own change is at least 85% of the baked direction's
COMBO_MAX_OUTSIDE = 1.3  # and it moves the skin outside the region at most 30% more (or 0.15 mm RMS more)


def solve(gnm: GNM, cfg: dict) -> Solution:
    sv = cfg["solver"]
    comps = [n for n in gnm.identity_names if gnm.region_of(n) == sv.get("components", "head")]
    cidx = [gnm.identity_names.index(c) for c in comps]
    B = gnm.identity_basis[cidx].astype(np.float64) * 1000.0  # (C, V, 3) mm per σ
    C = len(comps)
    lm = config_landmarks(cfg)
    normals = vertex_normals(gnm.template, gnm.triangles)
    sliders = cfg["slider"]
    measures = [build_measure(s["measure"], lm, gnm, normals) for s in sliders]
    guards = cfg.get("guard", [])
    guard_measures = [build_measure(g["measure"], lm, gnm, normals) for g in guards]

    def jac(m: Measure) -> np.ndarray:
        return np.tensordot(B, m.grad / 1000.0, axes=([1, 2], [0, 1]))  # (C,) mm per σ

    J = np.stack([jac(m) for m in measures])  # (S, C)
    # what the OTHER sliders hold fixed for each slider: its own measurement, unless it names another (`held_measure`:
    # the slider aims at a new measurement while the others keep holding the old one, so their solutions stay put)
    Jh = np.stack([jac(build_measure(s["held_measure"], lm, gnm, normals)) if "held_measure" in s else J[k]
                   for k, s in enumerate(cfg["slider"])])
    G = np.stack([jac(m) for m in guard_measures]) if guards else np.zeros((0, C))

    # everything is measured on the outer skin (eyeballs, teeth and the mouth interior are free)
    ext = np.flatnonzero(gnm.vertex_groups["skin_exterior"])
    Bx = B[:, ext, :]  # (C, N, 3)
    Bf = Bx.reshape(C, -1)
    mirror = gnm.mirror[ext]
    pos = {v: i for i, v in enumerate(ext)}
    paired = np.array([m in pos for m in mirror])
    mi = np.array([pos[m] for m in mirror[paired]])
    flip = np.array([-1.0, 1.0, 1.0])
    asym = (Bx[:, paired, :] - Bx[:, mi, :] * flip).reshape(C, -1)
    Q_sym = asym @ asym.T / paired.sum()

    shipped = shipped_components(gnm)
    ship_idx = np.array([comps.index(c) for c in shipped])
    coeffs = np.zeros((len(sliders), C))
    outside, baked, choice = [], [], []
    ids = [s["id"] for s in sliders]
    held = [s.get("held", True) for s in sliders]  # held = false: nobody else has to keep this one fixed (e.g. head size)
    for k, s in enumerate(sliders):
        w_out = outside_weight(gnm, s["region"], float(s.get("falloff_mm", sv["falloff_mm"])), s.get("region_y"))
        outside.append(w_out)
        w = np.repeat(w_out[ext] ** 2, 3)
        Q_out = (Bf * w) @ Bf.T / max(w_out[ext].sum(), 1.0)
        free = set(s.get("free", []))
        others = [] if "*" in free else [j for j, o in enumerate(ids) if j != k and o not in free and held[j]]
        Jo = Jh[others]  # (O, C) the measurements this slider must leave alone
        H = np.stack([jac(build_measure(h, lm, gnm, normals)) for h in s.get("hold", [])]) if s.get("hold") else np.zeros((0, C))
        N = (np.eye(C)
             + float(s.get("lambda_out", sv["lambda_out"])) * Q_out
             + float(s.get("lambda_sym", sv["lambda_sym"])) * Q_sym
             + float(sv["w_cross"]) * Jo.T @ Jo
             + float(sv.get("w_guard", sv["w_cross"])) * G.T @ G
             + float(s.get("w_hold", sv.get("w_guard", sv["w_cross"]))) * H.T @ H)

        full = _direction(N, J[k], np.arange(C), s, sv)
        mix = _direction(N, J[k], ship_idx, s, sv)
        qf, qm = _quality(full, J[k], Jo, G, Q_out), _quality(mix, J[k], Jo, G, Q_out)
        good_mix = (abs(qm["own"]) >= COMBO_MIN_OWN * abs(qf["own"])
                    and qm["outside"] <= max(COMBO_MAX_OUTSIDE * qf["outside"], qf["outside"] + 0.15)
                    and abs(qm["own"]) >= 4 * qm["cross"]
                    and qm["guard"] <= 0.5 * MAX_GUARD_MM)
        bake = s.get("bake", "auto")
        use_mix = (bake is False) or (bake == "auto" and good_mix)
        coeffs[k] = mix if use_mix else full
        baked.append(not use_mix)
        choice.append({"baked": qf, "runtime": qm, "runtime_ok": bool(good_mix), "bake": bake})
    return Solution(ids, [s["name"] for s in sliders], comps, coeffs, J, np.linalg.norm(J, axis=1), measures, outside,
                    [ids if "*" in s.get("free", []) else list(s.get("free", [])) for s in sliders],
                    [g["id"] for g in guards], guard_measures, baked, shipped, choice, held)


def _direction(N: np.ndarray, Jk: np.ndarray, idx: np.ndarray, s: dict, sv: dict) -> np.ndarray:
    """Slider `s`'s solved direction on the components `idx` (the rest zero), scaled to weight 1.0."""
    u = np.zeros(len(Jk))
    u[idx] = np.linalg.solve(N[np.ix_(idx, idx)], Jk[idx])
    u /= np.linalg.norm(u)  # unit Mahalanobis length (coefficients are N(0, 1))
    if "scale_sigma" in s:  # hand override: weight 1.0 = exactly this many σ along u
        length = float(s["scale_sigma"])
    else:  # weight 1.0 = the feature at ±target_pop_sigma of the population, within max_sigma
        length = min(float(sv["target_pop_sigma"]) * np.linalg.norm(Jk) / float(Jk @ u), float(sv["max_sigma"]))
    return length * u


def _quality(c: np.ndarray, Jk: np.ndarray, Jo: np.ndarray, G: np.ndarray, Q_out: np.ndarray) -> dict:
    """Linearised effect of coefficients `c`: own change, largest held change, outside RMS and largest guard (mm)."""
    cross = np.abs(Jo @ c).max() if len(Jo) else 0.0
    guard = float(np.abs(G @ c).max()) if len(G) else 0.0
    return {"own": float(Jk @ c), "cross": float(cross), "outside": float(np.sqrt(max(c @ Q_out @ c, 0.0))), "guard": guard}



def evaluate(gnm: GNM, sol: Solution) -> list[dict]:
    """Measure what each slider really does at +1 and -1 (exact geometry, not the linearisation)."""
    ext = gnm.vertex_groups["skin_exterior"]
    base = np.array([m.value(gnm.template) for m in sol.measures])
    rows = []
    for k, sid in enumerate(sol.ids):
        d = sol.delta(gnm, k)
        plus = np.array([m.value(gnm.template + d) for m in sol.measures]) - base
        minus = np.array([m.value(gnm.template - d) for m in sol.measures]) - base
        change = (plus - minus) / 2  # symmetric estimate; the linear part
        linear = sol.J[k] @ sol.coefficients[k]
        cross = np.abs(change.copy())
        cross[k] = 0
        j = int(np.argmax(cross))
        strict = cross.copy()  # leave out the measurements this slider is allowed to change (free = nested)
        for f in sol.free[k]:
            strict[sol.ids.index(f)] = 0
        for i, h in enumerate(sol.held):
            if not h:
                strict[i] = 0
        js = int(np.argmax(strict))
        guard = [abs((gm.value(gnm.template + d) - gm.value(gnm.template - d)) / 2) for gm in sol.guard_measures]
        far = ext & (sol.outside[k] >= 0.999)
        mag = np.linalg.norm(d, axis=1) * 1000.0
        rows.append({
            "id": sid, "name": sol.names[k],
            "own_mm": float(change[k]), "plus_mm": float(plus[k]), "minus_mm": float(minus[k]),
            "pop_sigma_mm": float(sol.pop_sigma[k]),
            "efficiency": float(change[k] / (np.linalg.norm(sol.coefficients[k]) * sol.pop_sigma[k])),
            "cross_mm": float(cross[j]), "cross_id": sol.ids[j],
            "cross_strict_mm": float(strict[js]), "cross_strict_id": sol.ids[js],
            "ratio": float(abs(change[k]) / max(cross[j], 1e-9)),
            "outside_rms_mm": float(np.sqrt(np.mean(mag[far] ** 2))) if far.any() else 0.0,
            "outside_max_mm": float(mag[far].max()) if far.any() else 0.0,
            "max_mm": float(mag[ext].max()),
            "lin_error": float(abs(linear - change[k]) / max(abs(change[k]), 1e-9)),
            "asym": float(abs(plus[k] + minus[k]) / max(abs(change[k]), 1e-9)),  # +1 vs -1 imbalance
            "sigma": float(np.linalg.norm(sol.coefficients[k])),
            "guards_mm": {gid: float(v) for gid, v in zip(sol.guard_ids, guard)},
            "all_mm": change.tolist(),
        })
    return rows


def coverage(gnm: GNM, sol: Solution, samples: int = 400, seed: int = 7) -> dict:
    """How much of what the raw sliders can do the semantic sliders can do too.

    Random faces over the shipped raw head_* components (z ~ N(0, 1), the Advanced sliders' space) are fitted
    with the semantic directions by least squares (sliders unbounded); coverage = 1 − residual² / total² of the
    outer-skin displacement. Also per raw component: how much of that one slider's shape the semantic set reproduces."""
    ext = gnm.vertex_groups["skin_exterior"]
    ship = [gnm.identity_names.index(c) for c in sol.shipped]
    Braw = gnm.identity_basis[ship][:, ext, :].reshape(len(ship), -1).astype(np.float64)  # (R, 3N)
    M = np.stack([sol.delta(gnm, k)[ext].ravel() for k in range(len(sol.ids))]).astype(np.float64)  # (S, 3N)
    G = M @ M.T + 1e-12 * np.eye(len(M))

    def explained(D: np.ndarray) -> np.ndarray:  # D (n, 3N) -> fraction of each row reproduced
        W = np.linalg.solve(G, M @ D.T)  # (S, n)
        R = D - W.T @ M
        return 1.0 - (R ** 2).sum(1) / (D ** 2).sum(1)

    rng = np.random.default_rng(seed)
    Z = rng.standard_normal((samples, len(ship)))
    D = Z @ Braw
    W = np.linalg.solve(G, M @ D.T)
    total = float(1.0 - ((D - W.T @ M) ** 2).sum() / (D ** 2).sum())
    per = explained(Braw)
    return {"random_faces": total, "per_raw": {c: float(v) for c, v in zip(sol.shipped, per)}}


def write_report(rows: list[dict], sol: Solution, path: Path, cover: dict | None = None) -> str:
    lines = [
        "# Semantic sliders — what each one does at weight +1",
        "",
        "own = change of the slider's own measurement (mm, mean of +1 and −1); "
        "cross = the largest change of any other measurement; outside = movement of the skin beyond the "
        "slider's region (+ falloff); guards = the largest change of a guard measurement (" + ", ".join(sol.guard_ids) + ", held "
        "fixed by every slider); length = Mahalanobis length of the direction at +1; efficiency = own change ÷ what the model allows at this σ "
        "(‖u‖ × population σ); lin. = linearisation error.",
        "",
        "shipped as = baked (its own morph target in head.glb) or runtime (a mix of the raw head_* targets, no extra "
        "bytes; chosen when it does nearly as well).",
        "",
        "| slider | shipped as | own Δ mm (pop. σ) | largest cross Δ mm (which) | own / cross | cross, nested excluded | guards Δ mm | outside RMS / max mm | max anywhere mm | length σ | efficiency | lin. |",
        "|---|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for k, r in enumerate(rows):
        lines.append(
            f"| {r['name']} | {'baked' if sol.baked[k] else 'runtime'} | {r['own_mm']:+.2f} ({r['own_mm'] / r['pop_sigma_mm']:.1f}σ) | {r['cross_mm']:.2f} ({r['cross_id']}) | "
            f"{r['ratio']:.1f}× | {r['cross_strict_mm']:.2f} ({r['cross_strict_id']}) | "
            f"{max(r['guards_mm'].values(), default=0.0):.2f} | "
            f"{r['outside_rms_mm']:.2f} / {r['outside_max_mm']:.2f} | {r['max_mm']:.2f} | {r['sigma']:.1f} | "
            f"{r['efficiency'] * 100:.0f}% | {r['lin_error'] * 100:.1f}% |")
    if cover:
        lines += ["", "## Coverage of the raw sliders", "",
                  f"Random faces over the {len(sol.shipped)} raw head sliders: the semantic sliders reproduce "
                  f"**{cover['random_faces'] * 100:.0f}%** of the skin movement (least squares, sliders unbounded).", "",
                  "| raw slider | reproduced |", "|---|---:|"]
        for c, v in sorted(cover["per_raw"].items(), key=lambda kv: kv[1]):
            lines.append(f"| {c} | {v * 100:.0f}% |")
    lines += ["", "## Cross-talk matrix (mm change of each measurement, columns, when a slider, rows, is at +1)", ""]
    short = [i[:10] for i in sol.ids]
    lines.append("| slider | " + " | ".join(short) + " |")
    lines.append("|---|" + "---:|" * len(short))
    for r in rows:
        cells = [f"**{v:+.2f}**" if i == sol.ids.index(r["id"]) else f"{v:+.2f}" for i, v in enumerate(r["all_mm"])]
        lines.append(f"| {r['name']} | " + " | ".join(cells) + " |")
    text = "\n".join(lines) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return text


# quality gates: the own change must dominate every non-nested measurement,
# guards must hold, and the linear model must describe the geometry
MIN_RATIO = 4.0  # own change ≥ 4 × the largest other (non-nested) change
MAX_GUARD_MM = 0.2
MAX_LIN_ERROR = 0.05


def check(rows: list[dict]) -> list[str]:
    out = []
    for r in rows:
        if abs(r["own_mm"]) < MIN_RATIO * r["cross_strict_mm"]:
            out.append(f"{r['id']}: own {r['own_mm']:+.2f} mm < {MIN_RATIO:g}× {r['cross_strict_id']} {r['cross_strict_mm']:.2f} mm")
        for gid, v in r["guards_mm"].items():
            if v > MAX_GUARD_MM:
                out.append(f"{r['id']}: guard {gid} moved {v:.2f} mm")
        if r["lin_error"] > MAX_LIN_ERROR:
            out.append(f"{r['id']}: linearisation error {r['lin_error'] * 100:.1f}%")
    return out



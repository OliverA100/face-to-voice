CELLS = {"metal": 0, "metal2": 1, "pad": 2, "tip": 3, "cord": 4, "hinge": 5}


def cell_uv(name: str) -> tuple[float, float]:
    i = CELLS[name]
    return 0.5 + (i % 4 + 0.5) / 8.0, (i // 4 + 0.5) / 2.0


# --- lens outlines (mm, lens-local: u away from the nose, v up, centred on the lens box) ----------------------------


def superellipse(a_out, a_in, b_top, b_bot, n, N=720) -> np.ndarray:
    """n = squareness per quadrant (outer-top, inner-top, inner-bottom, outer-bottom); 2 = ellipse, large = box."""
    t = np.linspace(0, 2 * np.pi, N, endpoint=False)
    c, s = np.cos(t), np.sin(t)
    q = np.where(s >= 0, np.where(c >= 0, 0, 1), np.where(c < 0, 2, 3))
    nn = np.asarray(n, float)[q]
    u = np.where(c >= 0, a_out, a_in) * np.sign(c) * np.abs(c) ** (2 / nn)
    v = np.where(s >= 0, b_top, b_bot) * np.sign(s) * np.abs(s) ** (2 / nn)
    return np.stack([u, v], 1)


def rounded_polygon(sides: int, a: float, b: float, rot: float, iterations: int = 4) -> np.ndarray:
    t = np.arange(sides) / sides * 2 * np.pi + rot
    p = np.stack([np.cos(t), np.sin(t)], 1)
    for _ in range(iterations):  # Chaikin: corner cutting → rounded corners
        q = np.roll(p, -1, 0)
        p = np.stack([0.8 * p + 0.2 * q, 0.2 * p + 0.8 * q], 1).reshape(-1, 2)
    p /= np.abs(p).max(0)
    return p * (a, b)


def outline(shape: str, W: float, H: float, nasal: float = 0.0) -> np.ndarray:
    """`nasal` (mm): how far the lower nose-side corner is cut away diagonally, as plastic frames are, so the rim
    clears the side of the nose where it widens (without it the frame rests on that corner, ~1 cm off the face)."""
    a, b = W / 2, H / 2
    if shape == "round":
        p = superellipse(a, a, b, b, (2, 2, 2, 2))
    elif shape == "oval":
        p = superellipse(a, a, b, b, (2.3, 2.3, 2.3, 2.3))
    elif shape == "rect":
        p = superellipse(a, a, b, b, (4.2, 4.2, 4.2, 4.2))
    elif shape == "square":
        p = superellipse(a, a, b, b, (4.5, 4.5, 4.5, 4.5))
    elif shape == "panto":  # round below, a flatter brow line on top
        p = superellipse(a, a, b, b, (3.4, 3.4, 2.1, 2.1))
    elif shape == "browline":
        p = superellipse(a, a, b, b, (4.0, 3.4, 2.4, 2.6))
    elif shape == "dframe":  # flat top, round bottom, a squarer outer side
        p = superellipse(a, a, b, b, (5.0, 3.2, 2.2, 2.8))
    elif shape == "wayfarer":  # trapezoid: the top wider than the bottom, the outer top corner raised
        p = superellipse(a, a, b, b, (4.6, 3.6, 2.6, 3.0))
        p[:, 0] *= 1 + 0.12 * p[:, 1] / b
        p[:, 1] += 2.0 * np.clip(p[:, 0] / a, 0, None) ** 3 * np.clip(p[:, 1] / b, 0, None)
    elif shape == "cateye":  # outer top corner swept up and out
        p = superellipse(a, a * 0.95, b, b * 0.9, (5.0, 3.0, 2.2, 2.0))
        lift = np.clip(p[:, 0] / a, 0, None) ** 4 * np.clip(p[:, 1] / b + 0.2, 0, None)
        p[:, 1] += 9.0 * lift
        p[:, 0] += 4.0 * lift
        p[:, 0] -= 0.12 * a * np.clip(p[:, 0] / a, 0, None) * np.clip(-p[:, 1] / b, 0, None)  # outer bottom tucked in
        p[:, 1] -= 0.25 * np.clip(-p[:, 0] / a, 0, None) * b * np.clip(p[:, 1] / b, 0, None)  # the inner top slopes down
    elif shape == "aviator":  # teardrop: straight-ish top, deep outer bottom, inner side slanting
        p = superellipse(a, a * 0.92, b * 0.78, b * 1.0, (3.0, 3.6, 1.7, 2.1))
        low = np.clip(-p[:, 1] / b, 0, None)
        p[:, 0] += 5.0 * low ** 1.5
        p[:, 1] += 0.08 * b * np.clip(-p[:, 0] / a, 0, None)
    elif shape == "hexagon":
        p = rounded_polygon(6, a, b, 0.0)
    elif shape == "octagon":
        p = rounded_polygon(8, a, b, np.pi / 8)
    else:
        raise ValueError(f"unknown lens shape {shape!r}")
    p -= (p.max(0) + p.min(0)) / 2  # centred on its box
    if nasal:
        a_in = -p[:, 0].min()
        low = np.clip((-p[:, 1] - 0.05 * b) / (0.95 * b), 0, 1) ** 1.3  # 0 at mid-height … 1 at the bottom
        p[:, 0] += nasal * low * np.clip(-p[:, 0] / a_in, 0, 1) ** 2  # only the nose side moves, outwards
    return resample_closed(p, 120)


def resample_closed(p: np.ndarray, n: int) -> np.ndarray:
    """n points evenly spaced along a closed polyline, counter-clockwise, starting at the outer middle."""
    if np.sum(p[:, 0] * np.roll(p[:, 1], -1) - np.roll(p[:, 0], -1) * p[:, 1]) < 0:
        p = p[::-1]
    q = np.vstack([p, p[:1]])
    seg = np.linalg.norm(np.diff(q, axis=0), axis=1)
    s = np.concatenate([[0], np.cumsum(seg)])
    t = np.linspace(0, s[-1], n, endpoint=False)
    out = np.stack([np.interp(t, s, q[:, 0]), np.interp(t, s, q[:, 1])], 1)
    start = np.argmin(np.abs(np.arctan2(out[:, 1], out[:, 0])))
    return np.roll(out, -start, 0)


def outward_normals(p: np.ndarray) -> np.ndarray:
    """Unit outward normals of a counter-clockwise closed polyline (smoothed over neighbours)."""
    t = np.roll(p, -1, 0) - np.roll(p, 1, 0)
    n = np.stack([t[:, 1], -t[:, 0]], 1)
    return n / np.linalg.norm(n, axis=1, keepdims=True)


# --- sweeps ---------------------------------------------------------------------------------------------------------


def rrect(s0: float, s1: float, z0: float, z1: float, r: float, k: int = 3) -> np.ndarray:
    """Closed rounded rectangle in (s, z), counter-clockwise, 4·(k+1) points."""
    r = min(r, (s1 - s0) / 2 - 1e-4, (z1 - z0) / 2 - 1e-4)
    pts = []
    for (cs, cz), a0 in (((s1 - r, z1 - r), 0.0), ((s0 + r, z1 - r), 0.5 * np.pi), ((s0 + r, z0 + r), np.pi), ((s1 - r, z0 + r), 1.5 * np.pi)):
        for j in range(k + 1):
            a = a0 + 0.5 * np.pi * j / k
            pts.append((cs + r * np.cos(a), cz + r * np.sin(a)))
    return np.array(pts)


def circle(r: float, k: int = 10) -> np.ndarray:
    a = np.linspace(0, 2 * np.pi, k, endpoint=False)
    return np.stack([r * np.cos(a), r * np.sin(a)], 1)


@dataclass
class Part:
    """A piece of mesh: positions (mm, frame space), triangles, UVs, and whether it is lens."""

    positions: np.ndarray
    triangles: np.ndarray
    uvs: np.ndarray
    lens: bool = False
    front: bool = True  # gets the front's face form and tilt (temples are placed after it)


def sweep(centres: np.ndarray, A: np.ndarray, B: np.ndarray, profiles: np.ndarray, closed: bool, uv) -> Part:
    """Rings of `profiles` (M, K, 2: offsets along A and B) round each path point; quads between rings, a dome-free
    open end is closed with a fan. `uv`: (M, K, 2) array or a fixed (u, v)."""
    M, K, _ = profiles.shape
    pos = centres[:, None, :] + profiles[..., :1] * A[:, None, :] + profiles[..., 1:] * B[:, None, :]
    tris = []
    rings = M if closed else M - 1
    for i in range(rings):
        i2 = (i + 1) % M
        for k in range(K):
            k2 = (k + 1) % K
            a, b, c, d = i * K + k, i2 * K + k, i2 * K + k2, i * K + k2
            tris += [(a, b, c), (a, c, d)]
    pos = pos.reshape(-1, 3)
    tris = np.array(tris)
    uvs = np.broadcast_to(np.asarray(uv, float), (M, K, 2)).reshape(-1, 2).copy() if np.ndim(uv) == 1 else uv.reshape(-1, 2)
    if not closed:  # caps
        for ring, flip in ((0, True), (M - 1, False)):
            c = len(pos)
            pos = np.vstack([pos, centres[ring]])
            uvs = np.vstack([uvs, uvs[ring * K]])
            fan = [(c, ring * K + (k + 1) % K, ring * K + k) if flip else (c, ring * K + k, ring * K + (k + 1) % K) for k in range(K)]
            tris = np.vstack([tris, fan])
    # outward winding: the first quad's normal must point away from its ring's centre
    p = pos[tris[:4]]
    nrm = np.cross(p[:, 1] - p[:, 0], p[:, 2] - p[:, 0]).sum(0)
    if np.dot(nrm, pos[tris[0, 0]] - centres[0]) < 0:
        tris = tris[:, ::-1]
    return Part(pos, tris, uvs)


def path_frames(path: np.ndarray, up=(0.0, 1.0, 0.0)) -> tuple[np.ndarray, np.ndarray]:
    """Per path point: A = sideways (horizontal, across the path), B = up-ish (perpendicular to the path and A)."""
    T = np.gradient(path, axis=0)
    T /= np.linalg.norm(T, axis=1, keepdims=True)
    A = np.cross(T, np.asarray(up))
    A /= np.linalg.norm(A, axis=1, keepdims=True)
    B = np.cross(A, T)
    return A, B


